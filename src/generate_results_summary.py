"""
Generate results summary: cross-cohort bar chart + lab drift degradation plots.
Reads from results/monte_carlo_benchmarks.csv (generated by run_monte_carlo_benchmarks.py).
"""
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.ticker as mticker
import numpy as np
import pandas as pd
import os

OUTPUT_DIR = "docs"
RESULTS_CSV = "results/monte_carlo_benchmarks.csv"


def load_benchmark_results():
    """Load benchmark CSV and extract mean AUROC values."""
    if not os.path.exists(RESULTS_CSV):
        print(f"Error: {RESULTS_CSV} not found. Run run_monte_carlo_benchmarks.py first.")
        exit(1)

    df = pd.read_csv(RESULTS_CSV)

    def clean(v):
        return float(str(v).split(' ')[0]) if pd.notna(v) else 0.0

    df['ROMA'] = df['ROMA Formula'].apply(clean)
    df['XGBoost'] = df['XGBoost'].apply(clean)
    df['RiskSLIM'] = df['Optimized RiskSLIM'].apply(clean)
    df['Noise_Pct'] = df['Noise'].str.rstrip('%').astype(int)
    return df


def plot_cross_cohort_bars(df):
    """Bar chart: RiskSLIM vs XGBoost vs ROMA at 5% noise across cohorts."""
    noise5 = df[df['Noise_Pct'] == 5]
    cohorts = noise5['Cohort'].unique()
    models = ['RiskSLIM', 'XGBoost', 'ROMA']
    colors = ['#2ecc71', '#3498db', '#e74c3c']

    fig, ax = plt.subplots(figsize=(10, 5.5), dpi=200)
    x = np.arange(len(cohorts))
    width = 0.22

    for i, (model, color) in enumerate(zip(models, colors)):
        vals = [noise5[noise5['Cohort'] == c][model].values[0] for c in cohorts]
        bars = ax.bar(x + i * width, vals, width, label=model, color=color, edgecolor='white', linewidth=0.5)
        for bar, v in zip(bars, vals):
            ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.008,
                    f"{v:.3f}", ha='center', va='bottom', fontsize=7)

    ax.set_ylabel("AUROC")
    ax.set_xticks(x + width)
    ax.set_xticklabels(cohorts, fontsize=9)
    ax.set_ylim(0.65, 1.02)
    ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.2f"))
    ax.legend(loc='lower right', fontsize=8, framealpha=0.9)
    ax.set_title("Cross-Cohort AUROC Comparison (5% Measurement Noise)", fontweight='bold', fontsize=12)
    ax.grid(axis='y', alpha=0.3, linestyle='--')
    fig.tight_layout()
    return fig


def plot_lab_drift(df):
    """Line plots: AUROC degradation under noise for each cohort."""
    cohorts = df['Cohort'].unique()
    fig, axes = plt.subplots(1, len(cohorts), figsize=(16, 5), sharey=True, dpi=200)

    colors = {'RiskSLIM': '#2ecc71', 'XGBoost': '#3498db', 'ROMA': '#e74c3c'}
    markers = {'RiskSLIM': 'o', 'XGBoost': '^', 'ROMA': 's'}

    for idx, cohort in enumerate(cohorts):
        ax = axes[idx] if len(cohorts) > 1 else axes
        sub = df[df['Cohort'] == cohort].sort_values('Noise_Pct')

        for model in ['RiskSLIM', 'XGBoost', 'ROMA']:
            ax.plot(sub['Noise_Pct'], sub[model],
                    marker=markers[model], markersize=5, linewidth=2,
                    color=colors[model], label=model)

        ax.set_title(cohort, fontweight='bold', fontsize=11)
        ax.set_xlabel("Noise Level (%)", fontsize=9)
        if idx == 0:
            ax.set_ylabel("AUROC", fontsize=9)
        ax.set_ylim(0.68, 0.96)
        ax.set_xticks([5, 10, 15, 20, 25, 30])
        ax.grid(alpha=0.3, linestyle='--')
        if idx == 0:
            ax.legend(fontsize=8, framealpha=0.9)

    fig.suptitle("AUROC Degradation Under Lab Measurement Noise", fontweight='bold', fontsize=13, y=1.02)
    fig.tight_layout()
    return fig


def build_markdown(df):
    """Generate results_summary.md with tables and key findings."""
    lines = []
    lines.append("# Ovarian Cancer ML — Results Summary")
    lines.append("")
    lines.append("## 1. Cross-Cohort AUROC (5% Measurement Noise)")
    lines.append("")

    noise5 = df[df['Noise_Pct'] == 5]
    cohorts = noise5['Cohort'].unique()
    models = ['RiskSLIM', 'XGBoost', 'ROMA']

    header = "| Model | " + " | ".join(cohorts) + " |"
    sep = "| :---- | " + " | ".join(":---:" for _ in cohorts) + " |"
    lines.append(header)
    lines.append(sep)
    for model in models:
        vals = [f"{noise5[noise5['Cohort']==c][model].values[0]:.4f}" for c in cohorts]
        lines.append(f"| {model} | " + " | ".join(vals) + " |")

    lines.append("")
    lines.append("![Cross-cohort AUROC](cross_cohort_auroc.png)")
    lines.append("")

    lines.append("## 2. Lab Drift Degradation (AUROC under proportional Gaussian noise)")
    lines.append("")

    for cohort in cohorts:
        lines.append(f"### {cohort}")
        lines.append("")
        sub = df[df['Cohort'] == cohort].sort_values('Noise_Pct')
        noise_labels = [f"{n}%" for n in sub['Noise_Pct'].values]
        header = "| Model | " + " | ".join(f"{n} Noise" for n in noise_labels) + " |"
        sep = "| :---- | " + " | ".join(":---:" for _ in noise_labels) + " |"
        lines.append(header)
        lines.append(sep)
        for model in models:
            vals = [f"{sub[sub['Noise_Pct']==n][model].values[0]:.4f}"
                    for n in sub['Noise_Pct'].values]
            lines.append(f"| {model} | " + " | ".join(vals) + " |")
        lines.append("")

    lines.append("![Lab drift degradation](lab_drift_degradation.png)")
    lines.append("")

    lines.append("## 3. Key Findings")
    lines.append("")
    lines.append("- **RiskSLIM** outperforms ROMA and XGBoost on internal (OG China) and "
                 "West China external validation at all noise levels.")
    lines.append("- **XGBoost** dominates on the Japanese cohort, where biomarker distributions "
                 "overlap substantially between cancer and benign patients.")
    lines.append("- **ROMA** provides a strong clinical baseline but is consistently "
                 "outperformed by the integer scorecard on cross-cohort validation.")
    lines.append("- **Lab drift robustness**: RiskSLIM degrades less under 30% measurement "
                 "noise than ROMA or XGBoost on the primary external validation (West China).")
    lines.append("- **Interpretability**: The scorecard uses only 7 non-zero integer weights "
                 "across 4 clinical features, deployable at bedside without software.")
    lines.append("")
    return "\n".join(lines)


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    df = load_benchmark_results()

    fig1 = plot_cross_cohort_bars(df)
    fig1.savefig(os.path.join(OUTPUT_DIR, "cross_cohort_auroc.png"), dpi=200, bbox_inches='tight')
    plt.close(fig1)
    print(f"  Saved: {OUTPUT_DIR}/cross_cohort_auroc.png")

    fig2 = plot_lab_drift(df)
    fig2.savefig(os.path.join(OUTPUT_DIR, "lab_drift_degradation.png"), dpi=200, bbox_inches='tight')
    plt.close(fig2)
    print(f"  Saved: {OUTPUT_DIR}/lab_drift_degradation.png")

    md = build_markdown(df)
    md_path = os.path.join(OUTPUT_DIR, "results_summary.md")
    with open(md_path, "w") as f:
        f.write(md)
    print(f"  Saved: {md_path}")

    print("\nDone.")


if __name__ == "__main__":
    main()
